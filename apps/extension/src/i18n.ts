const regionalLocales = ['ar', 'de', 'es', 'fr', 'id', 'ru'] as const;

export function localeFor(language: string): keyof typeof messages {
  const tag = language.replaceAll('_', '-').toLowerCase();
  const regional = regionalLocales.find((locale) => tag === locale || tag.startsWith(locale + '-'));
  if (regional) return regional;
  if (tag.startsWith('ja')) return 'ja';
  if (tag.startsWith('ko')) return 'ko';
  if (tag === 'pt' || tag === 'pt-br') return 'pt_BR';
  if (tag.startsWith('zh')) return /(?:hant|tw|hk|mo)/u.test(tag) ? 'zh_TW' : 'zh_CN';
  return 'en';
}
